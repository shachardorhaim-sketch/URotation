  function retrace(g, S) {
    const d = S.drag;
    let pos = S.pos, skip = -1;
    if (d && d.moved) { if (freeCell(S, S.hover, d.k)) { pos = S.pos.slice(); pos[d.k] = S.hover; } else skip = d.k; }
    if (S.carry >= 0) { if (freeCell(S, S.cur, S.carry)) { pos = S.pos.slice(); pos[S.carry] = S.cur; } else skip = S.carry; }
    S.tr = trace(S.L, pos, S.ori, skip);
    let lit = 0;
    S.L.tg.forEach((t, k) => {
      const on = (t.c ? (S.tr.hit[k] >> t.c) & 1 : S.tr.hit[k]) ? 1 : 0;
      if (on && !S.lit[k]) { S.litFx[k] = 1; if (g && !g.demo) { g.burst(ccx(S, t.i), ccy(S, t.i), { n: 14, color: [COL[t.c].glow, '#ffffff'], speed: 2.6, life: 30, gravity: 0 }); } }
      if (on) lit++;
      S.lit[k] = on;
    });
    if (g && !g.demo && lit !== S.litN && S.litN != null) { if (lit > S.litN) g.sfx('coin', { p: 0.9 + lit * 0.07 }); else g.tone({ f: 300, f2: 200, dur: 0.12, type: 'sine', vol: 0.1 }); }
    S.litN = lit;
    if (g && !S.won && !d && S.carry < 0 && lit === S.L.tg.length) win(g);
  }
