  // מהלך רגיל שנספר, והחלק מסומן בזהב
  function pickHint(S) {
    const L = S.L, G = L.goal, path = trace(L, G.pos, G.ori, -1).path, onPath = new Set(path.map(p => p.i));
    const away = q => {
      if (G.pos[q] !== S.pos[q] && freeCell(S, G.pos[q], q)) return G.pos[q];
      for (let i = 0; i < L.N; i++) if (i !== S.pos[q] && freeCell(S, i, q) && !onPath.has(i) && G.pos.indexOf(i) < 0) return i;
      return -1;
    };
    for (const p of path) {
      const k = G.pos.indexOf(p.i), here = S.pos.indexOf(p.i);
      if (here >= 0 && here !== k) { if (L.pc[here].mv) { const to = away(here); if (to >= 0) return ['m', here, to]; } continue; }
      if (k < 0) continue;
      if (here !== k) { if (L.pc[k].mv && freeCell(S, p.i, k)) return ['m', k, p.i]; continue; }
      if (L.pc[k].rt && S.ori[k] !== G.ori[k]) return ['r', k];
    }
    for (let k = 0; k < L.pc.length; k++) {
      if (L.pc[k].mv && S.pos[k] !== G.pos[k] && freeCell(S, G.pos[k], k)) return ['m', k, G.pos[k]];
      if (L.pc[k].rt && S.ori[k] !== G.ori[k] && onPath.has(G.pos[k])) return ['r', k];
    }
    return null;
  }
  function hint(g) {
    const S = g.s;
    if (S.won || S.drag) return;
    if (S.carry >= 0) { S.carry = -1; retrace(g, S); }
    const m = pickHint(S);
    if (!m) { g.sfx('error'); return; }
    if (m[0] === 'r' ? rotate(g, m[1]) : moveTo(g, m[1], m[2])) { S.hints++; S.glow[m[1]] = 2; g.sfx('power'); hud(g); }
  }
